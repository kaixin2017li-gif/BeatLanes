"""Tests for chart loading.

Both the chart that ships with the game and a set of broken files are checked:
a chart that parses but puts a note in lane 7 has to be rejected rather than
crash the game three seconds into a run.
"""

from __future__ import annotations

import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from beatlanes import config  # noqa: E402
from beatlanes.chart import Chart, ChartError, ChartNote, load_chart  # noqa: E402


def write_chart(directory: Path, payload) -> Path:
    path = directory / "chart.json"
    path.write_text(json.dumps(payload), encoding="utf-8")
    return path


class ShippedChartTests(unittest.TestCase):
    """The chart generated by tools/make_chart.py has to be playable."""

    def setUp(self):
        if not config.CHART_PATH.exists():
            self.skipTest(f"{config.CHART_PATH.name} not generated yet - run tools/make_chart.py")
        self.chart = load_chart(config.CHART_PATH)

    def test_notes_are_in_play_order(self):
        times = [note.time_ms for note in self.chart.notes]
        self.assertEqual(times, sorted(times))

    def test_indices_match_position(self):
        for position, note in enumerate(self.chart.notes):
            self.assertEqual(note.index, position)

    def test_every_lane_is_used(self):
        self.assertEqual(sum(self.chart.lane_counts), self.chart.note_count)
        self.assertTrue(all(count > 0 for count in self.chart.lane_counts), self.chart.lane_counts)

    def test_all_lanes_are_inside_the_window(self):
        for note in self.chart.notes:
            self.assertGreaterEqual(note.lane, 0)
            self.assertLess(note.lane, config.LANE_COUNT)

    def test_notes_start_after_the_intro(self):
        self.assertGreater(self.chart.notes[0].time_ms, 0)

    def test_tempo_is_recorded(self):
        self.assertAlmostEqual(self.chart.bpm, 120.0)


class BrokenChartTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.directory = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def test_missing_file(self):
        with self.assertRaises(ChartError):
            load_chart(self.directory / "nope.json")

    def test_not_json(self):
        path = self.directory / "bad.json"
        path.write_text("{ this is not json", encoding="utf-8")
        with self.assertRaises(ChartError):
            load_chart(path)

    def test_no_notes(self):
        with self.assertRaises(ChartError):
            load_chart(write_chart(self.directory, {"title": "empty", "notes": []}))

    def test_lane_out_of_range(self):
        payload = {"notes": [{"time": 100, "lane": config.LANE_COUNT}]}
        with self.assertRaises(ChartError):
            load_chart(write_chart(self.directory, payload))

    def test_negative_time(self):
        payload = {"notes": [{"time": -1, "lane": 0}]}
        with self.assertRaises(ChartError):
            load_chart(write_chart(self.directory, payload))

    def test_missing_fields(self):
        payload = {"notes": [{"lane": 0}]}
        with self.assertRaises(ChartError):
            load_chart(write_chart(self.directory, payload))

    def test_note_that_is_not_an_object(self):
        payload = {"notes": [1000]}
        with self.assertRaises(ChartError):
            load_chart(write_chart(self.directory, payload))


class OrderingTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.directory = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def test_notes_are_sorted_and_reindexed(self):
        payload = {
            "title": "out of order",
            "bpm": 90,
            "notes": [
                {"time": 3000, "lane": 1},
                {"time": 1000, "lane": 3},
                {"time": 2000, "lane": 0},
            ],
        }
        chart = load_chart(write_chart(self.directory, payload))
        self.assertEqual([note.time_ms for note in chart.notes], [1000, 2000, 3000])
        self.assertEqual([note.index for note in chart.notes], [0, 1, 2])
        self.assertEqual([note.lane for note in chart.notes], [3, 0, 1])

    def test_same_moment_is_ordered_by_lane(self):
        payload = {
            "notes": [
                {"time": 500, "lane": 3},
                {"time": 500, "lane": 0},
                {"time": 500, "lane": 2},
            ]
        }
        chart = load_chart(write_chart(self.directory, payload))
        self.assertEqual([note.lane for note in chart.notes], [0, 2, 3])

    def test_chart_length_is_the_last_note(self):
        payload = {"notes": [{"time": 100, "lane": 0}, {"time": 9000, "lane": 1}]}
        chart = load_chart(write_chart(self.directory, payload))
        self.assertEqual(chart.length_ms, 9000)

    def test_missing_title_falls_back_to_the_filename(self):
        payload = {"notes": [{"time": 100, "lane": 0}]}
        chart = load_chart(write_chart(self.directory, payload))
        self.assertEqual(chart.title, "chart")

    def test_chart_is_a_value(self):
        chart = Chart(title="t", bpm=120.0, notes=(ChartNote(0, 0, 100),))
        self.assertEqual(chart.note_count, 1)
        self.assertEqual(chart.length_ms, 100)


if __name__ == "__main__":
    unittest.main()
